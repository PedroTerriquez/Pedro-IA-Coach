export function resolveImageByKeywords(name: string) {
  if (!name) return null
  const norm = _normExercise(name)
  const tokens = norm.split(/\s+/).filter((t) => t.length > 2)
  if (tokens.length === 0) return null

  const equip = EQUIPMENT_RULES.find((r) => r.test(norm))
  const equipPrefix = equip ? equip.prefix.toLowerCase() : null

  let best = null
  let bestScore = 0

  for (const dir of FREE_EXERCISE_DIRS) {
    const dl = dir.toLowerCase()
    let score = 0

    if (equipPrefix && dl.startsWith(equipPrefix)) score += 0.3

    let matches = 0
    for (const t of tokens) {
      if (dl.includes(t)) {
        matches++
      } else {
        const engKeys = SPANISH_TO_EN_KEY[t]
        if (engKeys && engKeys.some((k: string) => dl.includes(k))) matches++
      }
    }
    score += (matches / tokens.length) * 0.7

    if (score > bestScore) {
      bestScore = score
      best = dir
    }
  }

  return bestScore >= 0.3 ? best : null
}

// Entries where the free-exercise-db directory exists but the photo shows wrong content
// (e.g., Cable_Seated_Lateral_Raise shows a bench press). Skips both dictionary image
// and keyword resolver, falling through to GIF fallback.
const SKIP_KEYWORD = new Set([
  'elevaciones-laterales-polea',
  'smith-machine-rdl',
])

export function resolveExerciseMedia(exercise: any) {
  const entry = exercise?.dictId ? getEntryById(exercise.dictId) : null
  const skipId = entry?.id
  const override = skipId ? GYMVISUAL_OVERRIDES[skipId] : undefined
  let usedGymvisual = false

  // 1. User override
  let imgUrl = exercise?.imgUrl || ''
  if (!imgUrl && override?.image) {
    imgUrl = _GV(override.image)
    usedGymvisual = true
  }
  if (!imgUrl) {
    // 2. Dictionary entry image (skip if image is known-wrong)
    const dictImage = entry?.image || getExerciseImageFromDictionary(exercise?.name || '') || ''
    if (dictImage && !SKIP_KEYWORD.has(skipId)) {
      const dirMatch = dictImage.match(/\/exercises\/(.+?)\/0\.jpg$/)
      if (dirMatch && FREE_EXERCISE_DIRS.has(dirMatch[1])) {
        imgUrl = dictImage
      }
    }
  }

  // 3. Keyword-based resolver (skip if directory exists but image is wrong)
  if (!imgUrl && !SKIP_KEYWORD.has(skipId)) {
    const keywordDir = resolveImageByKeywords(exercise?.name || '')
    if (keywordDir) imgUrl = _IMG(keywordDir)
  }

  let gifUrl = entry?.gif || getExerciseGifUrl(exercise?.name || '') || null
  if (override?.gif) {
    gifUrl = _GV(override.gif)
    usedGymvisual = true
  }

  // 4. GIF fallback — use GIF as static image when no valid photo
  if (!imgUrl && gifUrl) imgUrl = gifUrl

  return { imgUrl: imgUrl || '', gifUrl, attribution: usedGymvisual ? GYMVISUAL_ATTRIBUTION : null }
}

